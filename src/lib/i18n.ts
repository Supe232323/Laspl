const catalogs: Record<Locale, Dict> = { en, es, fr, de, pt, zh, ja };

function detectLocale(): Locale {
  try {
    const saved = localStorage.getItem("laspl-locale");
    if (saved && saved in catalogs) return saved as Locale;
  } catch {
    // ignore
  }
  if (typeof navigator !== "undefined") {
    const lang = (navigator.language || "en").slice(0, 2).toLowerCase();
    if (lang in catalogs) return lang as Locale;
  }
  return "en";
}

export const locale = writable<Locale>(detectLocale());

locale.subscribe((l) => {
  try {
    localStorage.setItem("laspl-locale", l);
    if (typeof document !== "undefined") {
      document.documentElement.lang = l === "zh" ? "zh-CN" : l;
    }
  } catch {
    // ignore
  }
});

function interpolate(str: string, params?: Record<string, string | number>): string {
  if (!params) return str;
  return str.replace(/\{(\w+)\}/g, (_, key: string) =>
    params[key] !== undefined ? String(params[key]) : `{${key}}`
  );
}

/** Translate a key. Reactive when used with $t in templates via the derived store. */
export function t(key: string, params?: Record<string, string | number>): string {
  const l = get(locale);
  const dict = catalogs[l] ?? en;
  const raw = dict[key] ?? en[key] ?? key;
  return interpolate(raw, params);
}

/** Reactive translator — use as $i18n(key) or bind $locale and call t(). */
export const i18n = derived(locale, ($locale) => {
  const dict = catalogs[$locale] ?? en;
  return (key: string, params?: Record<string, string | number>) => {
    const raw = dict[key] ?? en[key] ?? key;
    return interpolate(raw, params);
  };
});

export function setLocale(l: Locale) {
  locale.set(l);
}
